"""Compile native smoker definitions into OTC's existing provider contract.

Inputs are final, normally generated BP sources, in highest pack priority first
order. This only emits recipe data; it never packages, tests or operates a world.
"""
import argparse
import json
from pathlib import Path
import re

ITEM_ID = re.compile(r'[a-z0-9_.-]+:[a-z0-9_./-]+')


def item(value, *, output=False):
    count = 1
    if isinstance(value, dict):
        if set(value) - {'item', 'count', 'data'} or value.get('data', 0) != 0:
            raise ValueError('Item tags, metadata and alternatives need their actual resolver')
        count = value.get('count', 1)
        value = value.get('item')
    if not isinstance(value, str) or not ITEM_ID.fullmatch(value):
        raise ValueError('Expected one native item identifier')
    if type(count) is not int or not 1 <= count <= 64 or (not output and count != 1):
        raise ValueError('OTC requires one input and an output count in 1..64')
    return value, count


def compile_recipes(packs):
    """Retain native recipe identity and equal-route aliases, without food guesses."""
    definitions, sources = {}, []
    for pack in packs:
        pack = Path(pack).resolve()
        if not (pack / 'manifest.json').is_file():
            raise ValueError('Expected a behavior pack source: ' + str(pack))
        for path in sorted((pack / 'recipes').rglob('*.json')):
            document = json.loads(path.read_text(encoding='utf-8-sig'))
            for kind, recipe in document.items():
                if not kind.startswith('minecraft:recipe_') or not isinstance(recipe, dict):
                    continue
                identifier = recipe.get('description', {}).get('identifier')
                if not isinstance(identifier, str) or not ITEM_ID.fullmatch(identifier):
                    raise ValueError('Missing native recipe identity: ' + str(path))
                # A higher pack's definition replaces this ID even when it stops
                # being a smoker recipe. Different IDs remain distinct aliases.
                if identifier in definitions:
                    previous = definitions[identifier]
                    if previous['pack'] == str(pack) and previous['recipe'] != recipe:
                        raise ValueError('Ambiguous recipe ID inside one pack: ' + identifier)
                    continue
                definitions[identifier] = {'pack': str(pack), 'kind': kind,
                                           'recipe': recipe, 'path': str(path)}

    groups, routes = {}, {}
    for identifier, definition in definitions.items():
        recipe = definition['recipe']
        tags = recipe.get('tags', [])
        if definition['kind'] != 'minecraft:recipe_furnace' or 'smoker' not in tags:
            continue
        if not isinstance(tags, list) or any(not isinstance(tag, str) for tag in tags):
            raise ValueError('Invalid station tags: ' + definition['path'])
        input_id, _ = item(recipe['input'])
        output_id, count = item(recipe['output'], output=True)
        provider = identifier.split(':', 1)[0]
        if provider == 'minecraft':
            raise ValueError('Native vanilla overrides require an explicit priority contract: ' + identifier)
        # Keep existing registry arbitration: no new winner is invented for two
        # different results. Equal routes retain every native recipe ID.
        route = (output_id, count)
        if input_id in routes and routes[input_id] != (provider, route):
            raise ValueError('Conflicting smoker input requires source resolution: ' + input_id)
        routes[input_id] = (provider, route)
        groups.setdefault(provider, []).append({
            'id': identifier, 'process': 'smoking', 'input': input_id,
            'output': output_id, 'count': count})
        sources.append({'id': identifier, 'provider': provider, 'input': input_id,
                        'output': output_id, 'count': count, 'tags': tags,
                        'pack': definition['pack'], 'path': definition['path'],
                        'native_recipe': recipe})

    snapshots = [
        {'version': 1, 'provider': provider, 'catalog': 'main',
         'recipes': sorted(recipes, key=lambda row: row['id'])}
        for provider, recipes in sorted(groups.items())
    ]
    return snapshots, sources


def render(snapshots):
    return ('// SPDX-License-Identifier: GPL-3.0-only\n'
            '// Generated by tools/generate_smoking_recipes.py from native recipe JSON.\n'
            '// Regenerate from selected BP sources; do not edit this data.\n'
            'export const NATIVE_SMOKING_PROVIDERS = Object.freeze(' +
            json.dumps(snapshots, ensure_ascii=False, indent=2) +
            '.map(snapshot => Object.freeze({ ...snapshot, recipes: Object.freeze(\n'
            '  snapshot.recipes.map(recipe => Object.freeze(recipe))) })));\n').encode()


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--pack', type=Path, action='append', required=True,
                        help='Final BP source; repeat in highest priority first order')
    parser.add_argument('--output', type=Path, required=True)
    parser.add_argument('--provenance', type=Path, required=True)
    args = parser.parse_args()
    snapshots, sources = compile_recipes(args.pack)
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.provenance.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_bytes(render(snapshots))
    args.provenance.write_text(json.dumps(sources, ensure_ascii=False, indent=2) + '\n')
    print(json.dumps({'providers': len({row['provider'] for row in snapshots}),
                      'routes': len({row['input'] for row in sources}), 'native_definitions': len(sources),
                      'output': str(args.output)}, ensure_ascii=False))


if __name__ == '__main__':
    main()
