"""Share an author's native smoker recipes with OTC and Grilling.

The pure compiler accepts effective BP-relative bytes. The public CLI copies an
existing BP/RP pair to a new location and uses Core's existing paired-release
planner. Original author inputs and OTC runtime are never rewritten.
"""
import argparse
import hashlib
import importlib.util
import io
import json
from pathlib import Path, PurePosixPath
import posixpath
import re
import zipfile


MODULE_PATH = 'scripts/otc_smoking_provider.js'
MARKER = '// Generated by Order To Cook tools/build_smoking_provider.py.\n'
ITEM_ID = re.compile(r'^[a-z0-9_.-]+:[a-z0-9_./-]+$')


def _item(value, *, output=False):
    if isinstance(value, str):
        return (value, 1) if ITEM_ID.fullmatch(value) else None
    if not isinstance(value, dict) or set(value) - ({'item', 'count'} if output else {'item'}):
        return None
    item, count = value.get('item'), value.get('count', 1)
    if not isinstance(item, str) or not ITEM_ID.fullmatch(item):
        return None
    if type(count) is not int or not 1 <= count <= 64:
        return None
    return item, count


def _message(snapshot):
    # ASCII JSON makes Python length identical to the Script Event code-unit limit.
    return json.dumps(snapshot, separators=(',', ':'), ensure_ascii=True)


def _catalogs(recipes):
    catalogs = []
    for provider in sorted({row['id'].split(':', 1)[0] for row in recipes}):
        batch = {'version': 1, 'provider': provider, 'catalog': 'native_smoker_0', 'recipes': []}
        part = 0
        for row in recipes:
            if row['id'].split(':', 1)[0] != provider:
                continue
            candidate = {**batch, 'recipes': [*batch['recipes'], row]}
            if len(_message(candidate)) > 2048:
                if not batch['recipes']:
                    raise ValueError('One smoker recipe exceeds the Script Event limit')
                catalogs.append(batch)
                part += 1
                candidate = {**batch, 'catalog': f'native_smoker_{part}', 'recipes': [row]}
                if len(_message(candidate)) > 2048:
                    raise ValueError('One smoker recipe exceeds the Script Event limit')
            batch = candidate
        if batch['recipes']:
            catalogs.append(batch)
    return catalogs


def _publisher(catalogs):
    return (MARKER + "import { system, world, ItemTypes } from '@minecraft/server';\n" +
            'const catalogs = ' + _message(catalogs) + ';\n' + """
let loaded = false;
function publish(target) {
  if (!loaded) return;
  const grilling = target !== 'otc' && ItemTypes.get('kaleidoscope_grilling:secret_skewer');
  for (const snapshot of catalogs) {
    const recipes = snapshot.recipes.filter(recipe =>
      ItemTypes.get(recipe.input) && ItemTypes.get(recipe.output));
    if (target !== 'grilling') {
      system.sendScriptEvent('ordertocook:smoking_recipes_v1', JSON.stringify({ ...snapshot, recipes }));
    }
    if (grilling && recipes.length) {
      system.sendScriptEvent('kaleidoscope_grilling:register_secret_compat', JSON.stringify({
        smoking: recipes.map(({ input, output }) => ({ input, output }))
      }));
    }
  }
}
system.afterEvents.scriptEventReceive.subscribe(event => {
  if (event.sourceType !== 'Server') return;
  if (event.id === 'ordertocook:request_smoking_recipes_v1') {
    system.run(() => publish('otc'));
  } else if (event.id === 'kaleidoscope_grilling:request_secret_compat') {
    system.run(() => publish('grilling'));
  }
});
world.afterEvents.worldLoad.subscribe(() => {
  loaded = true;
  system.run(publish);
});
""").encode()


def compile_smoking_provider(bp_files):
    """Return changed files and a source report; no I/O, author whitelist or timer.

    Only one-input native smoker recipes with exact item IDs are representable
    by OTC V1. Identical alternatives coalesce; competing recipes are reported
    and omitted instead of choosing an unproved winner. Foreign/vanilla inputs,
    tags, item data and extra recipe conditions are not flattened.
    """
    skipped, candidates, duplicates, unsupported_inputs = [], [], [], set()
    for path, raw in sorted(bp_files.items()):
        if not path.startswith('recipes/') or not path.endswith('.json'):
            continue
        try:
            document = json.loads(raw)
        except (ValueError, UnicodeError):
            skipped.append({'path': path, 'reason': 'unreadable_recipe_json'})
            continue
        recipe = document.get('minecraft:recipe_furnace') if isinstance(document, dict) else None
        if not isinstance(recipe, dict):
            continue
        tags = recipe.get('tags')
        if not isinstance(tags, list) or 'smoker' not in tags:
            continue
        description = recipe.get('description')
        ident = description.get('identifier') if isinstance(description, dict) else None
        source, result = _item(recipe.get('input')), _item(recipe.get('output'), output=True)
        reason = None
        if set(recipe) - {'description', 'tags', 'input', 'output', 'unlock', 'priority'}:
            reason = 'unsupported_recipe_fields'
        elif not isinstance(ident, str) or not ITEM_ID.fullmatch(ident) or not source or not result:
            reason = 'unsupported_item_recipe'
        elif ident.split(':', 1)[0] == 'minecraft' or source[0].split(':', 1)[0] != ident.split(':', 1)[0]:
            reason = 'foreign_or_vanilla_input'
        if reason:
            skipped.append({'path': path, 'reason': reason})
            raw_input = recipe.get('input')
            known_input = raw_input.get('item') if isinstance(raw_input, dict) else raw_input
            if isinstance(known_input, str) and ITEM_ID.fullmatch(known_input):
                unsupported_inputs.add(known_input)
            continue
        candidates.append((path, {'id': ident, 'process': 'smoking', 'input': source[0],
                                  'output': result[0], 'count': result[1]}))

    by_id = {}
    for path, row in candidates:
        by_id.setdefault(row['id'], []).append((path, row))
    valid, conflicted_inputs = [], set(unsupported_inputs)
    for rows in by_id.values():
        if any(row != rows[0][1] for _, row in rows):
            skipped.extend({'path': path, 'reason': 'conflicting_recipe_id'} for path, _ in rows)
            conflicted_inputs.update(row['input'] for _, row in rows)
        else:
            valid.extend(rows)
    by_input = {}
    for path, row in valid:
        if row['input'] in conflicted_inputs:
            skipped.append({'path': path, 'reason': 'conflicting_smoker_input'})
            continue
        by_input.setdefault(row['input'], []).append((path, row))
    selected = []
    for rows in by_input.values():
        first_path, first = rows[0]
        if any((row['output'], row['count']) != (first['output'], first['count']) for _, row in rows):
            skipped.extend({'path': path, 'reason': 'conflicting_smoker_input'} for path, _ in rows)
            continue
        selected.append(first)
        duplicates.extend({'path': path, 'same_as': first_path} for path, _ in rows[1:])
    recipes = sorted(selected, key=lambda row: row['id'])
    report = {'updates': {}, 'removals': [], 'recipes': recipes, 'skipped': skipped, 'duplicates': duplicates}
    if not recipes and MODULE_PATH not in bp_files:
        return report

    manifest = json.loads(bp_files['manifest.json'])
    scripts = [row for row in manifest.get('modules', []) if row.get('type') == 'script']
    if len(scripts) != 1 or not any(row.get('module_name') == '@minecraft/server'
                                    for row in manifest.get('dependencies', [])):
        raise ValueError('A provider needs one existing script module and its server API dependency')
    entry = scripts[0].get('entry')
    if not isinstance(entry, str) or PurePosixPath(entry).is_absolute() or '..' in PurePosixPath(entry).parts or entry not in bp_files:
        raise ValueError('The existing script entry must resolve within this BP')
    if entry == MODULE_PATH:
        raise ValueError('The provider cannot replace the author script entry')
    original_module = bp_files.get(MODULE_PATH)
    if original_module is not None and not original_module.startswith(MARKER.encode()):
        raise ValueError('The provider output path already belongs to another source')
    original = bp_files[entry]
    text = original.decode('utf-8-sig')
    relative = posixpath.relpath(MODULE_PATH, posixpath.dirname(entry))
    if not relative.startswith('.'):
        relative = './' + relative
    import_line = f"import '{relative}';"
    if not recipes:
        report['removals'] = [MODULE_PATH]
        retained = ''.join(line for line in text.splitlines(keepends=True)
                           if line.rstrip('\r\n') != import_line)
        prefix = b'\xef\xbb\xbf' if original.startswith(b'\xef\xbb\xbf') else b''
        changed = prefix + retained.encode()
        if changed != original:
            report['updates'][entry] = changed
        return report
    module = _publisher(_catalogs(recipes))
    if module != original_module:
        report['updates'][MODULE_PATH] = module
    if import_line not in text.splitlines():
        newline = '\r\n' if '\r\n' in text else '\n'
        prefix = b'\xef\xbb\xbf' if original.startswith(b'\xef\xbb\xbf') else b''
        report['updates'][entry] = prefix + (import_line + newline + text).encode()
    return report


def _read_pack(root):
    files = {}
    for path in sorted(root.rglob('*')):
        if path.is_symlink():
            raise ValueError('Pack inputs must contain regular files and directories')
        if path.is_file():
            files[path.relative_to(root).as_posix()] = path.read_bytes()
    return files


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--bp', type=Path, required=True, help='Effective author BP directory')
    parser.add_argument('--rp', type=Path, required=True, help='Its corresponding RP directory')
    parser.add_argument('--core-source', type=Path, required=True, help='Public Senluo Bedrock Core checkout')
    parser.add_argument('--version', required=True, help='Fresh increasing paired MAJOR.MINOR.PATCH')
    parser.add_argument('--output', type=Path, required=True, help='New local directory; never an installed pack')
    args = parser.parse_args()
    output = args.output.resolve()
    roots = {'BP': args.bp.resolve(), 'RP': args.rp.resolve()}
    if output.exists() or any(output == root or root in output.parents for root in roots.values()):
        raise ValueError('Output must be new and outside the original inputs')
    packs = {side: _read_pack(root) for side, root in roots.items()}
    report = compile_smoking_provider(packs['BP'])
    if not report['recipes'] and not report['removals']:
        raise ValueError('No supported native smoker recipes; no modified pair is needed')
    spec = importlib.util.spec_from_file_location('senluo_paired_release', args.core_source / 'tools/paired_release.py')
    planner = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(planner)
    version = [int(part) for part in args.version.split('.')]
    manifests = planner.plan_pair({side: files['manifest.json'] for side, files in packs.items()}, version)
    packs['BP'].update(report['updates'])
    for path in report['removals']:
        del packs['BP'][path]
    for side in packs:
        packs[side]['manifest.json'] = manifests[side]['raw']
    output.mkdir(parents=True)
    pack_archives = {}
    for side, files in packs.items():
        buffer = io.BytesIO()
        with zipfile.ZipFile(buffer, 'w', compression=zipfile.ZIP_DEFLATED) as archive:
            for name, raw in sorted(files.items()):
                archive.writestr(name, raw)
        pack_archives[side + '.mcpack'] = buffer.getvalue()
    with zipfile.ZipFile(output / 'author-with-otc-smoking.mcaddon', 'w', compression=zipfile.ZIP_DEFLATED) as archive:
        for name, raw in pack_archives.items():
            archive.writestr(name, raw)
    summary = {key: value for key, value in report.items() if key != 'updates'}
    summary.update(version=version, changed_files=sorted(report['updates']),
                   source_manifests={side: hashlib.sha256((root / 'manifest.json').read_bytes()).hexdigest()
                                     for side, root in roots.items()})
    (output / 'smoking-provider.json').write_text(json.dumps(summary, indent=2) + '\n')
    print(json.dumps(summary, indent=2))


if __name__ == '__main__':
    main()
