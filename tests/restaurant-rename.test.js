for (const phase of ['chunk', 'root', 'silent-root', 'after-commit']) for (const currency of ['coins', 'custom']) test(`${currency} ${phase} persistence preserves canonical recovery and full native payment metadata`, async () => {
  const env = await named();
  if (currency === 'custom') configure(env, { currencyItem: 'minecraft:emerald' }, 'server');
  const stack = new FakeItem(currency === 'coins' ? 'ordertocook:chef_coin_5' : 'minecraft:emerald', 2);
  stack.nameTag = 'Money'; stack.setLore(['Full metadata']); stack.setDynamicProperty('test:nested', '{"kept":true}');
  stack.keepOnDeath = true; stack.lockMode = 'slot'; stack.damage = 9; stack.enchantments = [{ id: 'test:enchant', level: 2 }];
  env.player.container.setItem(5, stack); const tool = new FakeItem('minecraft:diamond_sword'); tool.damage = 18; env.player.container.setItem(9, tool);
  const before = inventory(env), root = 'ordertocook:r:' + env.restaurant.id; let old;
  const writes = [], setItem = env.player.container.setItem.bind(env.player.container);
  env.player.container.setItem = (slot, value) => { writes.push(slot); setItem(slot, value); };
  await rename(env, () => {
    old = saved(env); const set = env.world.setDynamicProperty; let failed = false;
    env.world.setDynamicProperty = (id, value) => {
      const target = phase === 'chunk' ? id.startsWith(root + ':part:') : id === root;
      if (failed || !target) return set(id, value);
      failed = true;
      if (phase === 'silent-root') return;
      if (phase === 'after-commit') set(id, value);
      throw Error('injected rename save failure');
    };
    return 'Confirmed Name';
  });
  assert.ok(!writes.includes(9), 'unrelated tools never written by payment or refund');
  if (phase === 'after-commit') {
    assert.equal(env.errors.length, 0); assert.equal(current(env), env.restaurant); assert.equal(saved(env).name, 'Confirmed Name');
    assert.equal(currency === 'coins' ? balance(env.player) : itemCount(env.player, 'minecraft:emerald'), currency === 'coins' ? 9 : 1);
  } else {
    assert.equal(env.errors.length, 1); assert.notEqual(current(env), env.restaurant); assert.deepEqual(current(env), old); assert.deepEqual(saved(env), old);
    assert.deepEqual(inventory(env), before);
  }
});
