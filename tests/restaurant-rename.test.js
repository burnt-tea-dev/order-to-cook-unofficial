const flush = () => new Promise(resolve => setImmediate(resolve));
async function fresh() {
  const env = await mainFixture([], { captureErrors: true });
  for (let slot = 0; slot < env.player.container.size; slot++) env.player.container.setItem(slot, undefined);
  return env;
}
async function rename(env, name) {
  env.system.currentTick += 4; env.formResponses.push(6, 0); env.textResponses.push(name);
  const event = { player: env.player, block: env.machine, isFirstEvent: true, cancel: false };
  for (const fn of env.world.beforeEvents.playerInteractWithBlock.subscriptions) fn(event);
  for (const fn of env.system.callbacks.splice(0)) fn();
  await flush();
}
async function named() { const env = await fresh(); await rename(env, 'First Kitchen'); return env; }
function coins(env, amount = 1) { env.player.container.setItem(5, new FakeItem('ordertocook:chef_coin_5', amount)); }
const current = env => env.store.getRestaurant(env.restaurant.id);

