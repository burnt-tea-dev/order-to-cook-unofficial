function inventory(env) { return Array.from({ length: env.player.container.size }, (_, slot) => env.player.container.getItem(slot)); }
function saved(env) {
  const root = 'ordertocook:r:' + env.restaurant.id, manifest = JSON.parse(env.properties.get(root));
  return JSON.parse(Array.from({ length: manifest.parts }, (_, index) => env.properties.get(`${root}:part:${manifest.buffer}:${index}`)).join(''));
}

